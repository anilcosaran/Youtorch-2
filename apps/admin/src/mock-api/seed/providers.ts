/** Providers; `cost30d` is filled in once the catalog exists (see seed/index.ts). */
export function seedProviders(now: number): ProviderRecord[] {
  return SEEDS.map(({ ageDays, credential, health, ...seed }) => ({
    ...seed,
    credential: {
      configured: credential.hint !== null,
      hint: credential.hint,
      source: credential.source,
      rotatedAt: credential.rotatedDaysAgo === null ? null : iso(now - credential.rotatedDaysAgo * DAY),
    },
    health: {
      state: health.state,
      successRate24h: health.successRate24h,
      p50Ms: health.p50Ms,
      incidents7d: health.incidents7d,
      checkedAt: health.checked ? iso(now - 4 * MINUTE) : null,
    },
    cost30d: 0,
    createdAt: iso(now - ageDays * DAY),
    updatedAt: iso(now - Math.min(ageDays, 3) * DAY - 5 * HOUR),
  }));
}
